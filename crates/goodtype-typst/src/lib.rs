pub const MAX_SOURCE_BYTES: usize = 1024 * 1024;
const MAX_WIDTH_PT: f64 = 10_000.0;

/// The header Goodtype writes above a Page text source when the writer picks a preset.
///
/// Generated by `presetHeader` in `apps/desktop/src/lib/page/presets.ts` and recognised here.
/// Two consumers ask this question — the export, which must not apply the shared style on top of
/// a source that already imports one, and the editor, which shifts analysis offsets past the
/// generated `goodtype_rhythm` prelude — and each carried its own copy of the test. A change to
/// the generated header would have made the export silently double-apply the style and the
/// editor silently stop shifting, neither of which fails loudly.
///
/// Whether a Page text source already carries the generated preset header.
pub fn has_managed_preset(source: &str) -> bool {
    page_source::managed_header(source).is_some()
}

/// Slack compiled around a preview so it is not clipped by its own page frame.
///
/// A Typst page with `height: auto` fits the content's *layout* box, and a line box runs from cap
/// height to baseline — so descenders drop below the frame, and accents, tall delimiters and
/// inline math rise above it. An SVG's viewBox is that frame, so everything outside it is cut
/// off. The PDF export never had the problem: there a block is placed on a page far larger than
/// itself, and Typst does not clip a block's overflow.
///
/// Compiling into a page this much wider with a margin to match keeps the text measure identical
/// to the export's `block(width:)` — the same line breaks — and gives the overflow somewhere to
/// land. [`CompileResult::width_pt`] and [`CompileResult::height_pt`] stay the size of the
/// content alone, so a caller draws the SVG at its full size offset by `-pad_pt` and the content
/// lands exactly where the export puts it.
pub const PREVIEW_PAD_PT: f64 = 16.0;

#[derive(Debug, Clone, PartialEq)]
pub struct CompileRequest {
    pub source: String,
    pub width_pt: f64,
    pub generation: u64,
    /// Allow downloading a Typst Universe package on a cache miss. Cached packages
    /// resolve either way; this only governs whether a request may be made.
    pub allow_remote_packages: bool,
}

#[derive(Debug, Clone, PartialEq, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct CompileResult {
    pub generation: u64,
    pub svg: Option<String>,
    /// Width of the content, excluding the [`PREVIEW_PAD_PT`] slack the SVG carries on each side.
    pub width_pt: Option<f64>,
    /// Height of the content, excluding the [`PREVIEW_PAD_PT`] slack the SVG carries on each side.
    pub height_pt: Option<f64>,
    /// How far the SVG extends past the content on every side. Draw it offset by `-pad_pt` to put
    /// the content back where the export places it.
    pub pad_pt: f64,
    pub diagnostics: Vec<Diagnostic>,
}

/// One completion candidate at a caret.
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct Completion {
    /// What is being completed: `function`, `parameter`, `symbol`, `package`, …
    pub kind: &'static str,
    /// For a math symbol, the glyph it renders as (`∑`), so it can be shown beside the name.
    pub symbol: Option<String>,
    pub label: String,
    /// Replacement text when it differs from the label; may contain `${…}` placeholders.
    pub apply: Option<String>,
    pub detail: Option<String>,
    /// Byte offset where the replacement starts, so the caller replaces the partial word.
    pub offset: usize,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct Hover {
    pub value: String,
    pub code: bool,
}

/// Complete at `cursor` (a byte offset) inside a block's source.
///
/// `explicit` marks a completion the user asked for (Ctrl+Space) rather than one triggered by
/// typing; Typst offers broader candidates in that case.
pub fn complete(
    notebook_root: &Path,
    source: String,
    cursor: usize,
    explicit: bool,
    allow_remote_packages: bool,
) -> Result<Vec<Completion>, CompileError> {
    let root = checked_root_and_source(notebook_root, &source)?;
    Ok(embedded::complete(
        &root,
        source,
        cursor,
        explicit,
        allow_remote_packages,
    ))
}

pub fn hover(
    notebook_root: &Path,
    source: String,
    cursor: usize,
    allow_remote_packages: bool,
) -> Result<Option<Hover>, CompileError> {
    let root = checked_root_and_source(notebook_root, &source)?;
    Ok(embedded::hover(
        &root,
        source,
        cursor,
        allow_remote_packages,
    ))
}

pub fn format_source(source: String) -> Result<String, CompileError> {
    if source.len() > MAX_SOURCE_BYTES {
        return Err(CompileError::SourceTooLarge(source.len()));
    }
    typstyle_core::Typstyle::default()
        .format_text(source)
        .render()
        .map_err(|error| CompileError::Format(error.to_string()))
}

fn checked_root_and_source(notebook_root: &Path, source: &str) -> Result<PathBuf, CompileError> {
    let root = notebook_root
        .canonicalize()
        .map_err(|_| CompileError::InvalidRoot(notebook_root.to_path_buf()))?;
    if !root.is_dir() {
        return Err(CompileError::InvalidRoot(root));
    }
    if source.len() > MAX_SOURCE_BYTES {
        return Err(CompileError::SourceTooLarge(source.len()));
    }
    Ok(root)
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct Diagnostic {
    pub severity: DiagnosticSeverity,
    pub message: String,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub line: Option<usize>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub column: Option<usize>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub end_line: Option<usize>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub end_column: Option<usize>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub snippet: Option<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub file: Option<String>,
    #[serde(skip)]
    pub(crate) range: Option<std::ops::Range<usize>>,
}

impl Diagnostic {
    /// An error with no source location, for failures outside any Typst file.
    pub fn error(message: impl Into<String>) -> Self {
        Self {
            severity: DiagnosticSeverity::Error,
            message: message.into(),
            line: None,
            column: None,
            end_line: None,
            end_column: None,
            snippet: None,
            file: None,
            range: None,
        }
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
#[serde(rename_all = "lowercase")]
pub enum DiagnosticSeverity {
    Error,
    Warning,
}

#[derive(Debug)]
pub enum CompileError {
    InvalidRoot(PathBuf),
    InvalidWidth(f64),
    SourceTooLarge(usize),
    Format(String),
}

impl std::fmt::Display for CompileError {
    fn fmt(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::InvalidRoot(path) => {
                write!(
                    formatter,
                    "Typst root is not a directory: {}",
                    path.display()
                )
            }
            Self::InvalidWidth(width) => write!(formatter, "invalid Typst width: {width}"),
            Self::SourceTooLarge(size) => {
                write!(
                    formatter,
                    "Typst source exceeds {MAX_SOURCE_BYTES} bytes: {size}"
                )
            }
            Self::Format(error) => write!(formatter, "Typst formatting failed: {error}"),
        }
    }
}

impl std::error::Error for CompileError {}

pub fn compile_block(
    notebook_root: &Path,
    request: &CompileRequest,
) -> Result<CompileResult, CompileError> {
    compile_block_inner(notebook_root, request, None)
}

/// Project dependencies resolve exclusively from granted virtual paths; packages retain their policy.
pub type GrantedFiles = std::collections::BTreeMap<String, Vec<u8>>;

pub fn compile_block_granted(
    notebook_root: &Path,
    request: &CompileRequest,
    files: &GrantedFiles,
) -> Result<CompileResult, CompileError> {
    compile_block_inner(notebook_root, request, Some(files))
}

fn compile_block_inner(
    notebook_root: &Path,
    request: &CompileRequest,
    files: Option<&GrantedFiles>,
) -> Result<CompileResult, CompileError> {
    compile_block_with(
        notebook_root,
        request,
        files,
        embedded::package_loader(request.allow_remote_packages),
    )
}

fn compile_block_with(
    notebook_root: &Path,
    request: &CompileRequest,
    files: Option<&GrantedFiles>,
    packages: &'static typst_kit::packages::SystemPackages,
) -> Result<CompileResult, CompileError> {
    let root = checked_root_and_source(notebook_root, &request.source)?;
    if !request.width_pt.is_finite() || request.width_pt <= 0.0 || request.width_pt > MAX_WIDTH_PT {
        return Err(CompileError::InvalidWidth(request.width_pt));
    }

    // `fill: none` rather than the default white: the padding is meant to be see-through, or
    // every block would wear a 16pt white halo over whatever it sits on. The settings are named
    // so a preamble placed before the content (a page template written as an ordinary Typst
    // header, which may well `#set page(paper: "a4", header: ...)`) can be followed by
    // `#set page(..goodtype_page)`, giving the page back to Goodtype without repeating numbers.
    let wrapper = format!(
        "#let goodtype_page = (width: {}pt, height: auto, margin: {PREVIEW_PAD_PT}pt, fill: none, \
         header: none, footer: none, numbering: none, background: none, foreground: none)\n\
         #set page(..goodtype_page)\n{}",
        request.width_pt + 2.0 * PREVIEW_PAD_PT,
        request.source
    );

    let prefix = wrapper.len() - request.source.len();
    let mut result = embedded::compile_block(
        &root,
        request.generation,
        wrapper,
        PREVIEW_PAD_PT,
        packages,
        files,
    );
    remap_diagnostics(
        &mut result,
        &request.source,
        prefix,
        0,
        request.source.len(),
    );
    Ok(result)
}

/// Map a copied source segment back to caller coordinates. Generated spans are deliberately omitted.
pub fn remap_diagnostics(
    result: &mut CompileResult,
    original: &str,
    generated_start: usize,
    original_start: usize,
    length: usize,
) {
    for d in &mut result.diagnostics {
        if d.file.is_some() {
            continue;
        }
        let range = d.range.take().and_then(|r| {
            (r.start >= generated_start && r.end <= generated_start + length).then(|| {
                r.start - generated_start + original_start..r.end - generated_start + original_start
            })
        });
        d.line = None;
        d.column = None;
        d.end_line = None;
        d.end_column = None;
        d.snippet = None;
        if let Some(r) = range.filter(|r| original.get(r.clone()).is_some()) {
            locate(d, original, r.clone());
            d.range = Some(r);
        }
    }
}

/// Fill a diagnostic's 1-based line/column span and bounded snippet from `text[range]`.
fn locate(d: &mut Diagnostic, text: &str, range: std::ops::Range<usize>) {
    let position = |offset: usize| {
        let before = &text[..offset];
        (
            Some(before.chars().filter(|&c| c == '\n').count() + 1),
            Some(before.rsplit('\n').next().unwrap_or("").chars().count() + 1),
        )
    };
    (d.line, d.column) = position(range.start);
    (d.end_line, d.end_column) = position(range.end);
    d.snippet = Some(text[range].chars().take(200).collect());
}

/// Point diagnostics raised inside an inlined preamble at the preset file itself, so a broken
/// template names its own file and line instead of an unplaceable generated span.
fn map_preamble_diagnostics(
    result: &mut CompileResult,
    preamble: &page_source::Preamble,
    start: usize,
) {
    for d in &mut result.diagnostics {
        if d.file.is_some() {
            continue;
        }
        let Some(range) = d.range.clone() else {
            continue;
        };
        if range.start < start || range.end > start + preamble.text.len() {
            continue;
        }
        let (Some(from), Some(to)) = (
            preamble.original_offset(range.start - start),
            preamble.original_offset(range.end - start),
        ) else {
            continue;
        };
        if from > to
            || !preamble.original.is_char_boundary(from)
            || !preamble.original.is_char_boundary(to)
        {
            continue;
        }
        locate(d, &preamble.original, from..to);
        d.file = Some(preamble.path.clone());
        d.range = None;
    }
}

/// Compile Page text as preview, export and the helper all see it: the shared composition,
/// diagnostics mapped to the editable source or, inside a preamble preset, to that preset file.
pub fn compile_page_text(
    root: &Path,
    page: &export::ExportPage,
    request: &CompileRequest,
) -> Result<CompileResult, String> {
    compile_page_text_with(
        root,
        page,
        request,
        None,
        embedded::package_loader(request.allow_remote_packages),
    )
    .map(|(result, _)| result)
}

fn compile_page_text_with(
    root: &Path,
    page: &export::ExportPage,
    request: &CompileRequest,
    files: Option<&GrantedFiles>,
    packages: &'static typst_kit::packages::SystemPackages,
) -> Result<(CompileResult, Option<page_source::PresetForm>), String> {
    let composed = export::compose_page_text(
        root,
        page,
        &request.source,
        files,
        request.allow_remote_packages,
    )?;
    let original_start = if composed.prepared.preamble.is_some() {
        composed.prepared.header_bytes
    } else {
        0
    };
    let body = &request.source[original_start..];
    let start = export::page_text_body_offset(page, &composed.source, body);
    let mut result = compile_block_with(
        root,
        &CompileRequest {
            source: composed.source.clone(),
            ..request.clone()
        },
        files,
        packages,
    )
    .map_err(|e| e.to_string())?;
    if let (Some(preamble), Some(preamble_start)) =
        (&composed.prepared.preamble, composed.preamble_start)
    {
        map_preamble_diagnostics(&mut result, preamble, preamble_start);
    }
    match start {
        Some(start) => remap_diagnostics(
            &mut result,
            &request.source,
            start,
            original_start,
            body.len(),
        ),
        None => remap_diagnostics(&mut result, &request.source, usize::MAX / 2, 0, 0),
    }
    Ok((result, composed.prepared.form))
}

